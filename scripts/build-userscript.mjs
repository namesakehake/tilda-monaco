import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { Script } from 'node:vm';

const root = new URL('../', import.meta.url);
const repository = 'https://github.com/namesakehake/tilda-monaco';
const downloadURL = 'https://raw.githubusercontent.com/namesakehake/tilda-monaco/main/dist/tilda-monaco.user.js';
const output = new URL('dist/tilda-monaco.user.js', root);
const check = process.argv.includes('--check');
if (process.argv.slice(2).some(argument => argument !== '--check')) {
  throw new Error('Usage: node scripts/build-userscript.mjs [--check]');
}

const [source, css] = await Promise.all([
  readFile(new URL('src/tilda-monaco.user.js', root), 'utf8'),
  readFile(new URL('src/tilda-monaco.css', root), 'utf8'),
]);
const header = source.match(/^\/\/ ==UserScript==\r?\n[\s\S]*?\/\/ ==\/UserScript==\r?\n/);
if (!header) throw new Error('Missing userscript header.');
const version = header[0].match(/^\/\/ @version\s+(\d+\.\d+\.\d+)\s*$/m)?.[1];
if (!version) throw new Error('Expected a stable @version such as 1.1.11.');

// Keep the public script's permissions and matches in sync with the source.
const metadata = header[0].trimEnd().split(/\r?\n/).filter(line =>
  !/^\/\/ @(?:resource|updateURL|downloadURL|homepageURL|supportURL)\b/.test(line) &&
  !/^\/\/ @grant\s+GM_getResourceText\s*$/.test(line),
);
metadata.splice(-1, 0,
  `// @homepageURL  ${repository}`,
  `// @supportURL   ${repository}/issues`,
  `// @updateURL    ${downloadURL}`,
  `// @downloadURL  ${downloadURL}`,
);

// Embed the exact CSS bytes as a string: JS and CSS install/update atomically.
const body = source.slice(header[0].length);
const resource = 'GM_getResourceText("tmlStyles")';
if (body.split(resource).length !== 2) {
  throw new Error('Expected exactly one tmlStyles resource read.');
}
const bundled = metadata.join('\n') + '\n\n' +
  '// Generated by scripts/build-userscript.mjs. Edit src/ and rebuild.\n' +
  body.replace(resource, () => JSON.stringify(css));
new Script(bundled, { filename: 'tilda-monaco.user.js' });

if (check) {
  const existing = await readFile(output, 'utf8').catch(error => {
    if (error.code === 'ENOENT') return null;
    throw error;
  });
  if (existing !== bundled) {
    throw new Error('dist is missing or outdated. Run node scripts/build-userscript.mjs.');
  }
  console.log(`dist matches src: ${version}`);
} else {
  await mkdir(new URL('dist/', root), { recursive: true });
  await writeFile(output, bundled);
  console.log(`Built dist/tilda-monaco.user.js: ${version}, ${Buffer.byteLength(bundled)} bytes`);
}
